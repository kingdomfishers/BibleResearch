import assert from 'node:assert/strict';
import { base,headers,chronology } from './chronology-client.mjs';
const args = (book,chapter,verse,model='theographic-verse-v1') => ({p_book:book,p_chapter:chapter,p_verse:verse,p_model_id:model});
const creation = await chronology(args(1,2,7,'adam-resurrection-30-v1'));
assert.equal(creation.status,'ok');
assert.equal(creation.summary.earliest_year,-3970);
assert.equal(creation.summary.label,'around 3971 BC (Year 0)');
assert.equal(creation.summary.millennium_first,1);
assert.equal(creation.has_archaeological_evidence,false);
assert.ok(creation.evidence.some(e => e.category==='textual' && e.relationship==='contextual'));
assert.ok(creation.evidence.some(e => e.category==='model_premise'));
assert.ok(creation.alternatives.some(e => e.model_id==='theographic-verse-v1' && e.earliest_year===-4003));
const later = await chronology(args(1,2,7,'adam-resurrection-33-v1'));
assert.equal(later.summary.label,'around 3968 BC (Year 3)');
const acts = await chronology(args(44,2,1));
assert.equal(acts.summary.earliest_year,33);
assert.ok(acts.alternatives.some(a=>a.axis==='mentioned_event' && a.earliest_year===30));
const archaeology = await chronology(args(12,18,13,'archaeology-pilot-v1'));
assert.equal(archaeology.summary.label,'around 701 BC (Year 3270)');
const artifact = archaeology.evidence.find(e=>e.category==='archaeological');
assert.equal(artifact.object_year,-690);
assert.equal(artifact.event_year,-700);
const competing = await chronology(args(12,18,13));
assert.ok(competing.evidence.some(e=>e.category==='archaeological' && e.relationship==='challenging'));
const john = await chronology(args(43,1,1));
assert.equal(john.assignment_status,'unresolved');
assert.equal(john.assertions.length,0);
const heading = await chronology(args(19,3,0));
assert.equal(heading.status,'ok');
assert.equal(heading.passage.is_heading,true);
assert.equal(heading.assignment_status,'unresolved');
const revision = await chronology(args(66,1,1));
assert.equal(revision.assertions[0].axis,'source_placement');
assert.equal(revision.summary.earliest_year,96);
assert.equal((await chronology(args(64,1,15))).status,'ok');
assert.equal((await chronology({...args(1,1,1),p_run_id:creation.run.id})).status,'release_unavailable');
assert.equal((await chronology({...args(1,1,1),p_run_id:'invalid'})).status,'invalid_run');
assert.equal((await chronology({...args(1,1,1),p_evidence_cursor:'1:2:3'})).status,'invalid_cursor');
assert.equal((await chronology({...args(1,1,1),p_model_id:'private-model'})).status,'invalid_model');
assert.equal((await chronology(args(67,1,1))).status,'invalid_reference');
assert.equal((await chronology(args(1,1,176))).status,'passage_not_found');
for (const packet of [creation,later,acts,archaeology,competing,john,heading,revision]) {
  assert.ok(Buffer.byteLength(JSON.stringify(packet))<=51200);
  assert.ok(packet.assertions.length<=20 && packet.evidence.length<=20);
  assert.ok(packet.models.every(m=>m.coverage.passages===31203));
}
const write = await fetch(`${base}/rest/v1/chronology_models`,{method:'POST',headers,body:JSON.stringify({id:'forbidden-client-write',name:'Must be rejected'})});
assert.ok([401,403].includes(write.status),'Anonymous chronology writes must be denied');
const publish = await fetch(`${base}/rest/v1/rpc/chronology_publish_run`,{method:'POST',headers,body:JSON.stringify({p_model_id:'theographic-verse-v1',p_label:'forbidden'})});
assert.ok([401,403,404].includes(publish.status),'Anonymous publication must be denied');
console.log('Chronology public RPC passed: source/scenario dates, archaeological scope, alternatives, headings, missing data, packet bounds and denied writes/publication.');
