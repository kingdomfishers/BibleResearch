// Canonical skill -> portable OpenAI/Gemini package + Edge-safe workflow module.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const skillRoot = path.join(root, 'skills/bible-research');
const output = path.join(root, '.artifacts/research-plugin/bible-research');
const manifest = JSON.parse(await fs.readFile(path.join(root, 'integrations/plugin.json'), 'utf8'));
const skill = await fs.readFile(path.join(skillRoot, 'SKILL.md'), 'utf8');
const contract = await fs.readFile(path.join(skillRoot, 'references/tool-contracts.md'), 'utf8');
const body = skill.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').trim();
if (!body.startsWith('# Bible research')) throw new Error('Invalid canonical research skill');
const instructions = body.split('## Further contract details')[0].trim() + '\n\n' + contract.trim();
const generated = [
  '// @file: supabase/functions/bible-mcp/research-workflow.ts',
  '// @feature: api', '// @tables: none', '// @candidates: none',
  '// @toc: logic:workflow', '', '// === @section:logic:workflow ===',
  '// Generated by scripts/build-research-plugin.mjs from the canonical skill. Do not hand-edit.',
  `export const WORKFLOW_VERSION = ${JSON.stringify(manifest.version)};`,
  `export const WORKFLOW_INSTRUCTIONS = ${JSON.stringify(instructions)};`, '',
].join('\n');
await fs.writeFile(path.join(root, 'supabase/functions/bible-mcp/research-workflow.ts'), generated);
await fs.mkdir(output, { recursive: true });
for (const file of ['plugin.json', 'mcp.json', 'gemini-extension.json', 'GEMINI.md']) {
  await fs.copyFile(path.join(root, 'integrations', file), path.join(output, file));
}
for (const file of ['SKILL.md', 'references/tool-contracts.md', 'agents/openai.yaml']) {
  const target = path.join(output, 'skills/bible-research', file);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.copyFile(path.join(skillRoot, file), target);
}
console.log(`Built BibleResearch ${manifest.version} at ${output}`);
