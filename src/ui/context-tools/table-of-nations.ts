function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function stripDiacriticsAndMarks(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f\u0591-\u05C7]/g, '')
    .trim();
}

const tribeByIdMap = new Map<string, BiblicalTribeEntry>();
const strongsToTribeMap = new Map<string, BiblicalTribeEntry>();
const originalToTribeMap = new Map<string, BiblicalTribeEntry>();
const matcherList: TribeMatcherMeta[] = [];

for (const entry of BIBLICAL_TRIBES) {
  tribeByIdMap.set(entry.id, entry);

  for (const rawCode of entry.strongs) {
    const norm = normalizeStrongsKey(rawCode);
    if (norm && !strongsToTribeMap.has(norm)) {
      strongsToTribeMap.set(norm, entry);
    }
  }

  const originalForms: string[] = [];
  if (entry.hebrew) {
    for (const part of entry.hebrew.split('/')) {
      const stripped = stripDiacriticsAndMarks(part);
      if (stripped) {
        originalForms.push(stripped);
        if (!originalToTribeMap.has(stripped)) {
          originalToTribeMap.set(stripped, entry);
        }
      }
    }
  }
  if (entry.greek) {
    for (const part of entry.greek.split('/')) {
      const stripped = stripDiacriticsAndMarks(part).toLowerCase();
      if (stripped) {
        originalForms.push(stripped);
        if (!originalToTribeMap.has(stripped)) {
          originalToTribeMap.set(stripped, entry);
        }
      }
    }
  }

  const override = DEMONYM_OVERRIDES[entry.id];
  const ciTerms = override?.ci ?? [];
  const csTerms = override?.cs ?? [];

  matcherList.push({
    entry,
    caseInsensitivePatterns: ciTerms.map(term => new RegExp(`\\b${escapeRegex(term)}\\b`, 'i')),
    caseSensitivePatterns: csTerms.map(term => new RegExp(`\\b${escapeRegex(term)}\\b`)),
    originalForms,
  });
}

// === @section:logic:detect ===
export function getTribeById(id: string): BiblicalTribeEntry | undefined {
  return tribeByIdMap.get(id);
}

export function detectTribeForWord(args: {
  strongs?: string;
  english?: string;
  original?: string;
}): BiblicalTribeEntry | null {
  if (args.strongs) {
    const norm = normalizeStrongsKey(args.strongs);
    const byStrongs = strongsToTribeMap.get(norm);
    if (byStrongs) return byStrongs;
  }

  if (args.original) {
    const cleaned = stripDiacriticsAndMarks(args.original);
    const byExact = originalToTribeMap.get(cleaned) ?? originalToTribeMap.get(cleaned.toLowerCase());
    if (byExact) return byExact;
  }

  if (args.english) {
    const text = args.english.trim();
    if (!text) return null;

    for (const meta of matcherList) {
      for (const re of meta.caseInsensitivePatterns) {
        if (re.test(text)) return meta.entry;
      }
      for (const re of meta.caseSensitivePatterns) {
        if (re.test(text)) return meta.entry;
      }
    }
  }

  return null;
}

export function detectTribesForPassage(
  strongsList: string[],
  verseTokens?: Array<{ strongs_nr: string; selected_english?: string | null; source_english?: string | null }>,
): BiblicalTribeEntry[] {
  const seenIds = new Set<string>();
  const detected: BiblicalTribeEntry[] = [];

  const pushUnique = (tribe: BiblicalTribeEntry | null) => {
    if (!tribe || seenIds.has(tribe.id)) return;
    seenIds.add(tribe.id);
    detected.push(tribe);
  };

  for (const code of strongsList) {
    pushUnique(detectTribeForWord({ strongs: code }));
  }

  if (verseTokens) {
    for (const token of verseTokens) {
      pushUnique(
        detectTribeForWord({
          strongs: token.strongs_nr,
          english: token.selected_english ?? token.source_english ?? undefined,
        }),
      );
      if (token.source_english && token.source_english !== token.selected_english) {
        pushUnique(detectTribeForWord({ english: token.source_english }));
      }
    }
  }

  return detected;
}
