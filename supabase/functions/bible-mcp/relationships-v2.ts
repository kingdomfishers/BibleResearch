async function decodePilotB64(rawB64: string): Promise<PilotBundle> {
  const cleanB64 = rawB64
    .trim()
    .split('\n')
    .map((line) => {
      const s = line.trim().replace(/^\d+:\s*/, '');
      return s.length > 100 && !s.endsWith('=') ? s.slice(s.length - 100) : s;
    })
    .join('');
  const bin = atob(cleanB64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate-raw'));
  return JSON.parse(await new Response(stream).text()) as PilotBundle;
}
